import { cpSync, existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { loadConfig } from "../config";
import type { LanguageKey, LocalDoctorSummary, UnitAgentConfig } from "../contracts";
import { sha256Hex } from "../core/context";
import { cleanRepoRelative, isSafeRealPathInsideRoot, normalizeSlashes } from "../core/paths";
import { extractTestRulesBlock, loadPromptTemplate } from "../llm";
import { runLocalDoctor, UNIT_AGENT_CLI_VERSION } from "./doctor";

export interface InitChatFileResult {
  path: string;
  action: "created" | "updated" | "unchanged" | "skipped_modified";
}

export interface RunInitChatOptions {
  repoRoot: string;
  workDir: string;
  configPath?: string;
  config?: UnitAgentConfig;
  force?: boolean;
  withTasks?: boolean;
  dryRun?: boolean;
  wasmDir?: string;
}

export interface RunInitChatResult {
  files: InitChatFileResult[];
  tasksSampleWritten: boolean;
  bundleCopied: boolean;
  doctor: LocalDoctorSummary;
}

function resolveChatTemplatesDir(): string {
  const moduleDir = path.dirname(fileURLToPath(import.meta.url));
  const candidates = [
    path.resolve(moduleDir, "templates", "chat"),
    path.resolve(moduleDir, "..", "..", "dist", "templates", "chat"),
    path.resolve(moduleDir, "..", "..", "templates", "chat"),
    path.resolve(process.cwd(), "templates", "chat"),
    path.resolve(process.cwd(), "dist", "templates", "chat"),
  ];
  for (const dir of candidates) {
    if (existsSync(path.join(dir, "unit-agent.agent.md.tmpl"))) return dir;
  }
  throw new Error(`Unable to locate templates/chat directory. Checked: ${candidates.join(", ")}`);
}

function stripJsonc(raw: string): string {
  let out = "";
  let inString = false;
  let escape = false;
  let i = 0;

  while (i < raw.length) {
    const ch = raw[i]!;
    const next = raw[i + 1];

    if (inString) {
      out += ch;
      if (escape) {
        escape = false;
      } else if (ch === "\\") {
        escape = true;
      } else if (ch === '"') {
        inString = false;
      }
      i += 1;
      continue;
    }

    if (ch === '"') {
      inString = true;
      out += ch;
      i += 1;
      continue;
    }

    if (ch === "/" && next === "/") {
      while (i < raw.length && raw[i] !== "\n") i += 1;
      continue;
    }

    if (ch === "/" && next === "*") {
      i += 2;
      while (i < raw.length && !(raw[i] === "*" && raw[i + 1] === "/")) i += 1;
      i += 2;
      continue;
    }

    out += ch;
    i += 1;
  }

  let cleaned = "";
  inString = false;
  escape = false;
  for (let j = 0; j < out.length; j += 1) {
    const c = out[j]!;
    if (inString) {
      cleaned += c;
      if (escape) escape = false;
      else if (c === "\\") escape = true;
      else if (c === '"') inString = false;
      continue;
    }
    if (c === '"') {
      inString = true;
      cleaned += c;
      continue;
    }
    if (c === ",") {
      let k = j + 1;
      while (k < out.length && /\s/.test(out[k]!)) k += 1;
      if (out[k] === "}" || out[k] === "]") {
        continue;
      }
    }
    cleaned += c;
  }

  return cleaned;
}

function stampContentHash(contentWithPlaceholder: string): string {
  const normalized = contentWithPlaceholder
    .replace(/\r\n/g, "\n")
    .replaceAll("{{version}}", UNIT_AGENT_CLI_VERSION)
    .replaceAll("{{hash}}", "__HASH_PLACEHOLDER__");
  const shortHash = sha256Hex(normalized).slice(0, 12);
  return contentWithPlaceholder.replaceAll("{{version}}", UNIT_AGENT_CLI_VERSION).replaceAll("{{hash}}", shortHash);
}

function isUnmodifiedGeneratedFile(existingContent: string): boolean {
  const markerRe = /<!--\s*generated by unit-agent init-chat\s+([^\s;]+)\s+hash=([a-f0-9]+);/;
  const m = markerRe.exec(existingContent);
  if (!m?.[2]) return false;
  const recordedHash = m[2];
  const normalized = existingContent
    .replace(/\r\n/g, "\n")
    .replace(`hash=${recordedHash}`, "hash=__HASH_PLACEHOLDER__");
  return sha256Hex(normalized).slice(0, 12) === recordedHash;
}

function renderTemplateText(raw: string, vars: Record<string, string>): string {
  return raw.replace(/\{\{([a-zA-Z0-9_]+)\}\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(vars, key) ? vars[key]! : match,
  );
}

export async function runInitChat(opts: RunInitChatOptions): Promise<RunInitChatResult> {
  const config = opts.config ?? loadConfig(opts.repoRoot, opts.configPath).config;
  const tmplDir = resolveChatTemplatesDir();

  const rawNodeCmd = config.local.nodeCommand.trim();
  const shellNodeCmd =
    /\s/.test(rawNodeCmd) && !(rawNodeCmd.startsWith('"') && rawNodeCmd.endsWith('"'))
      ? `"${rawNodeCmd.replace(/"/g, '\\"')}"`
      : rawNodeCmd;
  const cliCmd = `${shellNodeCmd} .unit-agent/bin/cli.js`;
  const enabledLangs = (["javascript", "python", "java"] as LanguageKey[]).filter((l) => config.languages[l]?.enabled);
  const testRules = extractTestRulesBlock().replaceAll(
    "{{maxTestsPerSymbol}}",
    String(config.limits.maxTestsPerSymbol),
  );
  const languageAddenda = enabledLangs.map((lang) => loadPromptTemplate(`${lang}.md`).trim()).join("\n\n");

  const vars: Record<string, string> = {
    cli: cliCmd,
    nodeCommand: shellNodeCmd,
    stagingDir: config.local.stagingDir.replace(/\\/g, "/"),
    toolsYamlList: JSON.stringify(config.local.chatTools),
    confirmBeforeRunRule: config.local.confirmBeforeRun
      ? "8. Before the first `local validate` in a session, tell the user the drafted tests will be executed on their machine and ask whether to go ahead."
      : "",
    testRules,
    languageAddenda,
  };

  const targetTemplates: Array<{ src: string; destRel: string }> = [
    { src: "unit-agent.agent.md.tmpl", destRel: ".github/agents/unit-agent.agent.md" },
    { src: "unit-tests.prompt.md", destRel: ".github/prompts/unit-tests.prompt.md" },
    { src: "unit-doctor.prompt.md", destRel: ".github/prompts/unit-doctor.prompt.md" },
    { src: "unit-repair.prompt.md", destRel: ".github/prompts/unit-repair.prompt.md" },
    { src: "unit-tests-staged.prompt.md", destRel: ".github/prompts/unit-tests-staged.prompt.md" },
    { src: "unit-tests-file.prompt.md", destRel: ".github/prompts/unit-tests-file.prompt.md" },
    { src: "unit-tests-apply.prompt.md", destRel: ".github/prompts/unit-tests-apply.prompt.md" },
  ];

  const fileResults: InitChatFileResult[] = [];
  for (const item of targetTemplates) {
    if (!isSafeRealPathInsideRoot(item.destRel, opts.repoRoot, { allowMissingLeaf: true })) {
      fileResults.push({ path: item.destRel, action: "skipped_modified" });
      continue;
    }
    const raw = readFileSync(path.join(tmplDir, item.src), "utf8");
    const preHash = renderTemplateText(raw, vars);
    const rendered = stampContentHash(preHash);
    const destAbs = path.join(opts.repoRoot, item.destRel);

    if (!existsSync(destAbs)) {
      if (!opts.dryRun) {
        mkdirSync(path.dirname(destAbs), { recursive: true });
        writeFileSync(destAbs, rendered, "utf8");
      }
      fileResults.push({ path: item.destRel, action: "created" });
      continue;
    }

    const existing = readFileSync(destAbs, "utf8");
    if (existing === rendered) {
      fileResults.push({ path: item.destRel, action: "unchanged" });
      continue;
    }
    if (!opts.force && !isUnmodifiedGeneratedFile(existing)) {
      fileResults.push({ path: item.destRel, action: "skipped_modified" });
      continue;
    }
    if (!opts.dryRun) {
      writeFileSync(destAbs, rendered, "utf8");
    }
    fileResults.push({ path: item.destRel, action: "updated" });
  }

  // VS Code tasks merge (tolerant JSONC)
  let tasksSampleWritten = false;
  if (opts.withTasks !== false) {
    const cliEntry =
      cleanRepoRelative(normalizeSlashes(path.relative(opts.repoRoot, path.join(opts.workDir, "bin", "cli.js")))) ||
      ".unit-agent/bin/cli.js";
    const jsonTaskVars: Record<string, string> = {
      rawNodeCommand: JSON.stringify(rawNodeCmd).slice(1, -1),
      cliEntry: JSON.stringify(cliEntry).slice(1, -1),
      nodeCommand: JSON.stringify(shellNodeCmd).slice(1, -1),
      cli: JSON.stringify(cliCmd).slice(1, -1),
      stagingDir: JSON.stringify(vars.stagingDir).slice(1, -1),
    };
    const rawTasks = renderTemplateText(readFileSync(path.join(tmplDir, "vscode-tasks.json"), "utf8"), jsonTaskVars);
    const uaTasksDoc = JSON.parse(rawTasks) as {
      version: string;
      tasks: Array<{ label: string; [k: string]: unknown }>;
      inputs?: Array<{ id: string; [k: string]: unknown }>;
    };

    const tasksRel = ".vscode/tasks.json";
    if (!isSafeRealPathInsideRoot(tasksRel, opts.repoRoot, { allowMissingLeaf: true })) {
      throw new Error(`Refusing unsafe write outside repoRoot: ${tasksRel}`);
    }
    const tasksPath = path.join(opts.repoRoot, ".vscode", "tasks.json");
    if (!existsSync(tasksPath)) {
      if (!opts.dryRun) {
        mkdirSync(path.dirname(tasksPath), { recursive: true });
        writeFileSync(tasksPath, `${JSON.stringify(uaTasksDoc, null, 2)}\n`, "utf8");
      }
      fileResults.push({ path: ".vscode/tasks.json", action: "created" });
    } else {
      const existingRaw = readFileSync(tasksPath, "utf8");
      try {
        const parsed = JSON.parse(stripJsonc(existingRaw)) as {
          version?: string;
          tasks?: Array<{ label?: string; [k: string]: unknown }>;
          inputs?: Array<{ id?: string; [k: string]: unknown }>;
          [k: string]: unknown;
        };
        const keptTasks = (parsed.tasks ?? []).filter(
          (t) => typeof t.label !== "string" || !t.label.startsWith("unit-agent:"),
        );
        const keptInputs = (parsed.inputs ?? []).filter((inp) => inp.id !== "unitAgentScope");
        const merged = {
          ...parsed,
          version: parsed.version ?? "2.0.0",
          tasks: [...keptTasks, ...uaTasksDoc.tasks],
          inputs: [...keptInputs, ...(uaTasksDoc.inputs ?? [])],
        };
        const mergedStr = `${JSON.stringify(merged, null, 2)}\n`;
        const changed = existingRaw !== mergedStr;
        if (changed && !opts.dryRun) {
          writeFileSync(tasksPath, mergedStr, "utf8");
        }
        fileResults.push({ path: ".vscode/tasks.json", action: changed ? "updated" : "unchanged" });
      } catch {
        const sampleRel = ".vscode/unit-agent.tasks.sample.json";
        if (!isSafeRealPathInsideRoot(sampleRel, opts.repoRoot, { allowMissingLeaf: true })) {
          throw new Error(`Refusing unsafe write outside repoRoot: ${sampleRel}`);
        }
        const samplePath = path.join(opts.repoRoot, ".vscode", "unit-agent.tasks.sample.json");
        if (!opts.dryRun) {
          mkdirSync(path.dirname(samplePath), { recursive: true });
          writeFileSync(samplePath, `${JSON.stringify(uaTasksDoc, null, 2)}\n`, "utf8");
        }
        tasksSampleWritten = true;
        fileResults.push({ path: ".vscode/unit-agent.tasks.sample.json", action: "created" });
      }
    }
  }

  // Ensure .gitignore contains .unit-agent/
  const gitignorePath = path.join(opts.repoRoot, ".gitignore");
  if (!opts.dryRun) {
    if (!isSafeRealPathInsideRoot(".gitignore", opts.repoRoot, { allowMissingLeaf: true })) {
      throw new Error("Refusing unsafe write outside repoRoot: .gitignore");
    }
    const existingIgnore = existsSync(gitignorePath) ? readFileSync(gitignorePath, "utf8") : "";
    const hasEntry = existingIgnore
      .split(/\r?\n/)
      .some((line) => line.trim() === ".unit-agent/" || line.trim() === ".unit-agent");
    if (!hasEntry) {
      const prefix = existingIgnore && !existingIgnore.endsWith("\n") ? "\n" : "";
      writeFileSync(gitignorePath, `${existingIgnore}${prefix}.unit-agent/\n`, "utf8");
    }
  }

  // Copy CLI bundle & wasm into .unit-agent/bin/
  let bundleCopied = false;
  if (!opts.dryRun) {
    const binDir = path.join(opts.workDir, "bin");
    mkdirSync(binDir, { recursive: true });
    const moduleDir = path.dirname(fileURLToPath(import.meta.url));
    const cliCandidates = [
      path.join(moduleDir, "cli.js"),
      path.resolve(moduleDir, "..", "..", "dist", "cli.js"),
      path.resolve(process.cwd(), "dist", "cli.js"),
    ];
    const srcCli = cliCandidates.find((c) => existsSync(c));
    if (srcCli) {
      const distRoot = path.dirname(srcCli);
      let sameDir: boolean;
      try {
        sameDir = realpathSync(distRoot) === realpathSync(binDir);
      } catch {
        sameDir = false;
      }
      if (!sameDir) {
        cpSync(srcCli, path.join(binDir, "cli.js"), { force: true });
        for (const extra of ["wasm", "prompts", "templates", "scripts", "unit-agent-jacoco.init.gradle"]) {
          const extraSrc = path.join(distRoot, extra);
          if (existsSync(extraSrc)) {
            cpSync(extraSrc, path.join(binDir, extra), { recursive: true, force: true });
          }
        }
      }
      bundleCopied = true;
    }
  }

  const doctor = await runLocalDoctor({
    repoRoot: opts.repoRoot,
    workDir: opts.workDir,
    configPath: opts.configPath,
    light: true,
    wasmDir: opts.wasmDir,
  });

  return {
    files: fileResults,
    tasksSampleWritten,
    bundleCopied,
    doctor,
  };
}
