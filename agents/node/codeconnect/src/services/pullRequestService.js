
const { Octokit } =
    require("@octokit/rest");
     
    class PullRequestService {

    constructor(
        githubToken
    ) {

        this.octokit =
            new Octokit({
                auth:
                    githubToken
            });
    }


    buildTitle(
        task
    ) {

        return (
            `CodeConnect: ${task.title}`
        );
    }

    buildDescription(
        task,
        files,
        validationResult
    ) {

        return `
## Task

${task.title}

${task.description}

## Files Modified

${files.join("\n")}

## Validation

${
    validationResult.success
        ? "PASSED"
        : "FAILED"
}

Generated by CodeConnect
`;
    }

    generateSummary(
        task,
        files,
        validationResult
    ) {

        return {

            title:
                this.buildTitle(
                    task
                ),

            description:
                this.buildDescription(
                    task,
                    files,
                    validationResult
                ),

            filesModified:
                files,

            validationPassed:
                validationResult.success
        };
    }
    async createPullRequest(
    owner,
    repo,
    head,
    base,
    summary
) {

    try {

        const response =
            await this.octokit
                .pulls
                .create({

                    owner,

                    repo,

                    title:
                        summary.title,

                    body:
                        summary.description,

                    head,

                    base
                });

        return {

            success: true,

            pullRequestNumber:
                response.data.number,

            pullRequestUrl:
                response.data.html_url
        };

    } catch (error) {

        return {

            success: false,

            error:
                error.message
        };
    }
}
}

module.exports =
    PullRequestService;