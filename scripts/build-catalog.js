#!/usr/bin/env node
/** Generates docs/CATALOG.md from the repository so it never drifts. */
import { readFile, readdir, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";

import { layout, repoRoot, listBindings, readBindingManifest, loadAgentFile, InstructionSet, listSkills, loadSkill, loadBundles } from "@l2/agent-core";

const root = repoRoot();
const dirs = layout(root);
const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const link = (p, label = path.basename(p)) => `[\`${label}\`](../${p})`;
const { marketplace, bundles } = await loadBundles(root);
const lines = ["# Catalog", "", "<!-- Generated by `npm run build`. Do not edit by hand. -->", ""];

lines.push("## Marketplace plugins", "", marketplace ? `Marketplace \`${marketplace.name}\` → \`${marketplace.repository}\`` : "_No bundles.json._", "",
  "| Plugin | Version | Status | Agents | Skills | Hooks | Instructions |", "| --- | --- | --- | --- | --- | --- | --- |");
for (const b of bundles) lines.push(`| **${esc(b.displayName ?? b.name)}** \`${b.name}\` | ${b.version} | ${b.status} | ${(b.agents ?? []).join(", ") || "-"} | ${(b.skills ?? []).join(", ") || "-"} | ${(b.hooks ?? []).join(", ") || "-"} | ${(b.instructions ?? []).join(", ") || "-"} |`);

lines.push("", "## L2 agents (automation)", "", "| Agent | Custom agent | Status | Lang | Model | Owner | Phase | Trigger |", "| --- | --- | --- | --- | --- | --- | --- | --- |");
for (const id of await listBindings(root)) {
  const { manifest: m } = await readBindingManifest(id, root);
  lines.push(`| **${esc(m.displayName ?? m.name)}** \`${m.name}\` v${m.version} | ${link(m.agent)} | ${m.status} | ${m.runtime?.language} | ${m.runtime?.model ?? "SDK default"} | ${esc(m.owner)} | ${esc(m.phase)} | ${esc(m.runtime?.trigger)} |`);
}

lines.push("", "## Custom agents", "", "| File | Description | Tools |", "| --- | --- | --- |");
for (const file of (await readdir(dirs.agents)).filter((f) => f.endsWith(".agent.md")).sort()) {
  const a = await loadAgentFile(path.join(dirs.agents, file));
  lines.push(`| ${link(`.github/agents/${file}`)} | ${esc(a.description)} | ${a.tools.join(", ") || "-"} |`);
}
const instructions = await InstructionSet.load(root);
lines.push("", "## Instructions", "", "| File | Applies to | Description |", "| --- | --- | --- |");
for (const i of instructions.files) lines.push(`| ${link(path.relative(root, i.filePath).replace(/\\/g, "/"))} | \`${esc(i.applyTo.join(", "))}\` | ${esc(i.description)} |`);
lines.push("", "## Skills", "", "| Skill | Description | Bundled assets |", "| --- | --- | --- |");
for (const name of await listSkills(root)) {
  const s = await loadSkill(name, root);
  lines.push(`| ${link(`.github/skills/${name}/SKILL.md`, name)} | ${esc(s.description)} | ${s.assets.map((a) => `\`${a}\``).join("<br>") || "-"} |`);
}
lines.push("", "## Hooks", "", "| File | Events |", "| --- | --- |");
if (existsSync(dirs.hooks)) {
  for (const file of (await readdir(dirs.hooks)).filter((f) => f.endsWith(".json")).sort()) {
    const config = JSON.parse(await readFile(path.join(dirs.hooks, file), "utf8"));
    lines.push(`| ${link(`.github/hooks/${file}`)} | ${Object.keys(config.hooks ?? {}).join(", ")} |`);
  }
}
await writeFile(path.join(root, "docs", "CATALOG.md"), `${lines.join("\n")}\n`);
console.log("Wrote docs/CATALOG.md");
